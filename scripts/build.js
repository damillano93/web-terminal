/* eslint-disable no-console */
const esbuild = require("esbuild");
const path = require("path");
const fs = require("fs");

const watch = process.argv.includes("--watch");

// Copy xterm.css from package to public/lib so the served HTML can <link> it
// (esbuild bundles JS + the CSS imported in JS, but our HTML also wants xterm.css separate).
fs.mkdirSync(path.join(__dirname, "..", "public", "lib"), { recursive: true });
const xtermCss = require.resolve("@xterm/xterm/css/xterm.css");
fs.copyFileSync(xtermCss, path.join(__dirname, "..", "public", "lib", "xterm.css"));

// Self-hosted terminal fonts (all SIL OFL, from @fontsource), so the picker's
// web fonts look the same on a Mac, an iPad and a phone without installing
// anything. Only latin + latin-ext, regular + bold. Browsers fetch a face only
// when something uses it, so the unused ones cost nothing.
const SERVED_FONTS = ["jetbrains-mono", "fira-code", "iosevka", "ibm-plex-mono"];
const fontsOut = path.join(__dirname, "..", "public", "fonts");
fs.mkdirSync(fontsOut, { recursive: true });
let fontCss = "/* Generated by scripts/build.js from @fontsource — do not edit. */\n";
for (const name of SERVED_FONTS) {
  const pkg = path.dirname(require.resolve(`@fontsource/${name}/package.json`));
  for (const weight of [400, 700]) {
    const css = fs.readFileSync(path.join(pkg, `${weight}.css`), "utf8");
    // One @font-face per subset, each preceded by a "/* <font>-<subset>-<w>-normal */" comment.
    for (const block of css.split(/(?=\/\* )/)) {
      const m = /\/\* (\S+-(latin|latin-ext)-\d+-normal) \*\//.exec(block);
      if (!m) continue;
      const file = `${m[1]}.woff2`;
      fs.copyFileSync(path.join(pkg, "files", file), path.join(fontsOut, file));
      fontCss += block
        .replace(/src:[^;]+;/, `src: url(/fonts/${file}) format('woff2');`)
        .trim() + "\n";
    }
  }
}
fs.writeFileSync(path.join(fontsOut, "fonts.css"), fontCss);

const ctx = {
  entryPoints: [path.join(__dirname, "..", "public", "app.src.js")],
  bundle: true,
  outfile: path.join(__dirname, "..", "public", "app.js"),
  format: "esm",
  platform: "browser",
  target: ["chrome120", "safari16", "firefox120"],
  sourcemap: true,
  minify: !watch,
  loader: {
    ".css": "css",
    ".wasm": "file",
    ".woff": "file",
    ".woff2": "file",
  },
  assetNames: "lib/[name]-[hash]",
  publicPath: "/",
  logLevel: "info",
};

if (watch) {
  esbuild.context(ctx).then((c) => c.watch());
} else {
  esbuild.build(ctx).catch((e) => { console.error(e); process.exit(1); });
}
